# -*- coding: utf-8 -*-
"""
phase_diagram_scan.py
=====================

Mott-lobe boundaries mu_c^{+-}(t) of the extended correlated-hopping
Bose-Hubbard chain (cf. Zechmann et al., PRB 2023, Fig. 1b and Eq. (20)),
cheap enough for a desktop CPU.

Idea
----
Particle number N and dipole moment P are conserved, so the chemical potential
only shifts energies: E(mu) = E0(N) - mu*N.  The integer-filling state n is the
grand-canonical ground state for

    mu_c^-(t) = E0(nL) - E0(nL-1)  <=  mu  <=  mu_c^+(t) = E0(nL+1) - E0(nL)

which is Eq. (20) of the paper.  Instead of a 2D grid in (t, mu) we therefore
need only 3 DMRG runs per (t, n): the Mott state and the states with one extra
particle / hole.  All runs are done at mu = 0.

Why a FINITE chain works here (the paper used iDMRG)
---------------------------------------------------
With dipole conservation a single extra particle (or hole) is a fracton: it
cannot move without emitting dipoles, which are gapped in the d-Mott phase.
Placing it in the middle of an open chain and fixing the (N, P) sector keeps it
there, so boundary energies cancel in E0(N+-1) - E0(N).
Benchmark (alpha=0, r=1, t/U=0.05, n=1, L=24, chi=80):
    finite DMRG  mu+ = 0.95956991,  mu- = -0.01001579
    exact diag.  mu+ = 0.95956991,  mu- = -0.01001579   (10-site ring)
in ~40 s on a slow 2-core VM.

(iDMRG was also tested: TeNPy's dipole symmetry is a beta feature for infinite
MPS and the doped runs N_uc = nL+-1 got stuck or broke; iDMRG with only N
conserved converged far too slowly.)

Results are appended to a CSV, already-computed points are skipped, so the
scan can be interrupted and resumed.  Typical use (from Restricted_model_extended):

    python phase_diagram_scan.py --alpha 3 --r 3 --L 32 --n_max 6 --chi 120 ^
        --n_t 16 --fillings 1 2 3 --workers 4

then  python plot_phase_diagram.py --alpha 3 --r 3
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from pathlib import Path


def _set_threads(n: int) -> None:
    # must happen BEFORE numpy is imported in the workers, otherwise every
    # worker uses all cores and the pool is slower than a serial run
    for var in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS",
                "NUMEXPR_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
        os.environ[var] = str(n)


FIELDS = [
    "alpha", "r", "U", "t", "L", "n_fill", "dN", "N", "n_max", "chi_max",
    "E0",            # total ground-state energy at mu = 0 in the (N, P) sector
    "E_mpo",         # <H> of the final MPS (diagnostic, should equal E0)
    "p_nmax",        # max over sites of the probability of n_max bosons (cutoff check)
    "S_mid",         # half-chain entanglement entropy
    "trunc_err",     # max truncation error of the last sweep
    "chi_reached", "n_sweeps", "converged", "wall_s",
]


def _key(row) -> tuple:
    return (int(row["alpha"]), int(row["r"]), round(float(row["U"]), 10),
            round(float(row["t"]), 10), int(row["L"]), int(row["n_fill"]),
            int(row["dN"]), int(row["n_max"]), int(row["chi_max"]))


def t_star(alpha: int, r: int, U: float = 1.0) -> float:
    """Mean-field bunching point: -2 n^2 sum_d t/d^alpha + U n^2/2 = 0."""
    return U / (4.0 * sum(d ** (-alpha) for d in range(1, r + 1)))


def run_point(job: dict) -> dict:
    """One finite DMRG run in a fixed (N, P) sector. Runs in a worker process."""
    import numpy as np
    from tenpy.algorithms import dmrg
    from tenpy.algorithms.mps_common import SubspaceExpansion
    from tenpy.linalg import np_conserved as npc
    from tenpy.networks.mps import MPS
    import model_extended

    L, n, dN, n_max, chi = job["L"], job["n_fill"], job["dN"], job["n_max"], job["chi_max"]
    t0 = time.time()
    model = model_extended.CorrelatedHoppingBoseModelFinite(dict(
        t=job["t"], U=job["U"], mu=0.0, L=L, n_max=n_max,
        conserve="dipole",            # -> also N; no 1e-5 symmetry-breaking hop
        filling=float(n), bc_MPS="finite",
        alpha=job["alpha"], r=job["r"],
    ))
    occ = [n] * L
    occ[L // 2] += dN                 # extra particle / hole in the middle
    psi = MPS.from_product_state(model.lat.mps_sites(), occ, bc="finite")

    params = {
        "trunc_params": {"chi_max": chi, "svd_min": job["svd_min"]},
        "chi_list": {0: max(16, chi // 4), 4: max(16, chi // 2), 8: chi},
        "max_E_err": job["max_E_err"],
        "max_S_err": 1e-3,
        "max_trunc_err": 1.0,         # don't abort; trunc_err is recorded and flagged
        "min_sweeps": 10,
        "max_sweeps": job["max_sweeps"],
        "max_hours": job["max_hours"],
        # the subspace expansion is essential: the pair hop acts on 3 sites
        # and cannot be generated by 2-site updates from a product state
        "mixer": SubspaceExpansion,
        "mixer_params": {"amplitude": 1e-3, "decay": 1.5, "disable_after": 20},
    }
    info = dmrg.run(psi, model, params)
    E0 = float(info["E"])            # finite DMRG: total energy
    E_mpo = float(model.H_MPO.expectation_value(psi))

    P_top = np.zeros((n_max + 1, n_max + 1)); P_top[n_max, n_max] = 1.0
    ops = [npc.Array.from_ndarray(P_top, [s.leg, s.leg.conj()], labels=["p", "p*"])
           for s in psi.sites]
    p_nmax = float(np.max(psi.expectation_value(ops)))
    stats = info.get("sweep_statistics", {})
    return dict(
        alpha=job["alpha"], r=job["r"], U=job["U"], t=job["t"], L=L,
        n_fill=n, dN=dN, N=n * L + dN, n_max=n_max, chi_max=chi,
        E0=E0, E_mpo=E_mpo, p_nmax=p_nmax,
        S_mid=float(psi.entanglement_entropy()[L // 2 - 1]),
        trunc_err=float(stats["max_trunc_err"][-1]) if stats.get("max_trunc_err") else float("nan"),
        chi_reached=int(max(psi.chi)),
        n_sweeps=len(stats.get("E", [])),
        converged=not bool(info.get("shelve", False)),
        wall_s=round(time.time() - t0, 1),
    )


def build_jobs(a) -> list[dict]:
    import numpy as np
    if a.t_values:
        ts = [float(x) for x in a.t_values]
    else:
        ts = [float(x) for x in np.linspace(a.t_min, a.t_max, a.n_t)]
    jobs = []
    for t in ts:
        for n in a.fillings:
            if n + 1 > a.n_max:
                raise SystemExit(f"n_max={a.n_max} too small for filling {n}")
            for dN in (0, +1, -1):
                jobs.append(dict(alpha=a.alpha, r=a.r, U=a.U, t=round(t, 10),
                                 L=a.L, n_fill=n, dN=dN, n_max=a.n_max,
                                 chi_max=a.chi, svd_min=a.svd_min,
                                 max_E_err=a.max_E_err, max_sweeps=a.max_sweeps,
                                 max_hours=a.max_hours))
    # small t first (cheap, Mott) -> early feedback
    jobs.sort(key=lambda j: (j["t"], j["n_fill"], j["dN"]))
    return jobs


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--alpha", type=int, required=True)
    p.add_argument("--r", type=int, required=True)
    p.add_argument("--U", type=float, default=1.0)
    p.add_argument("--L", type=int, default=32, help="chain length")
    p.add_argument("--n_max", type=int, default=6, help="boson cutoff per site")
    p.add_argument("--chi", type=int, default=120)
    p.add_argument("--svd_min", type=float, default=1e-10)
    p.add_argument("--max_E_err", type=float, default=1e-10)
    p.add_argument("--max_sweeps", type=int, default=80)
    p.add_argument("--max_hours", type=float, default=1.0, help="per run")
    p.add_argument("--t_min", type=float, default=0.0)
    p.add_argument("--t_max", type=float, default=None,
                   help="default: 0.98 x mean-field bunching point t*")
    p.add_argument("--n_t", type=int, default=16)
    p.add_argument("--t_values", nargs="*", default=None,
                   help="explicit list of t (overrides t_min/t_max/n_t)")
    p.add_argument("--fillings", type=int, nargs="+", default=[1, 2, 3])
    p.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    p.add_argument("--threads_per_worker", type=int, default=1)
    p.add_argument("--out", default="phase_diagram_data/lobes.csv")
    p.add_argument("--dry_run", action="store_true")
    a = p.parse_args()

    _set_threads(a.threads_per_worker)

    ts = t_star(a.alpha, a.r, a.U)
    if a.t_max is None:
        a.t_max = 0.98 * ts
    print(f"alpha={a.alpha}, r={a.r}: mean-field bunching t*/U = "
          f"1/(4 sum_d d^-alpha) = {ts / a.U:.6f}")
    if a.t_max > ts:
        print("  [WARN] t_max is beyond the grand-canonical bunching instability.")

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    done = set()
    if out.exists():
        with open(out, newline="") as f:
            done = {_key(r) for r in csv.DictReader(f)}
    jobs = [j for j in build_jobs(a) if _key(j) not in done]
    print(f"{len(jobs)} runs to do ({len(done)} already in {out}); "
          f"{a.workers} worker(s) x {a.threads_per_worker} thread(s)")
    if a.dry_run or not jobs:
        return

    new_file = not out.exists()
    if not new_file:
        with open(out, newline="") as f:
            header = next(csv.reader(f), [])
        if header != FIELDS:
            raise SystemExit(f"{out} was written by another version of this script "
                             f"(different columns); use a new --out file.")
    with open(out, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        if new_file:
            w.writeheader()

        def _write(res):
            w.writerow(res); f.flush()
            flag = "" if res["converged"] else "  [NOT CONVERGED]"
            if res["chi_reached"] >= res["chi_max"] and not res["trunc_err"] < 1e-8:
                flag += f"  [chi saturated, trunc_err={res['trunc_err']:.1e}]"
            if res["p_nmax"] > 1e-2:
                flag += f"  [n_max too small? p_nmax={res['p_nmax']:.1e}]"
            print(f"t={res['t']:.5f} n={res['n_fill']} dN={res['dN']:+d} "
                  f"E0={res['E0']:+.10f} chi={res['chi_reached']} "
                  f"{res['wall_s']:.0f}s{flag}", flush=True)

        if a.workers == 1:
            for j in jobs:
                _write(run_point(j))
        else:
            from concurrent.futures import ProcessPoolExecutor, as_completed
            with ProcessPoolExecutor(max_workers=a.workers) as ex:
                futs = {ex.submit(run_point, j): j for j in jobs}
                for fu in as_completed(futs):
                    try:
                        _write(fu.result())
                    except Exception as exc:          # keep the scan alive
                        j = futs[fu]
                        print(f"[ERROR] t={j['t']} n={j['n_fill']} dN={j['dN']}: {exc}",
                              file=sys.stderr, flush=True)


if __name__ == "__main__":
    main()
